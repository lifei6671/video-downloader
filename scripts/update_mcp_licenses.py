"""Collect the pinned MCP additions' complete license texts from Cargo's cache."""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Incremental packages introduced by mcp, plus its existing direct URI dependency.
# Keep explicit versions so an SDK/lockfile upgrade requires a licensing review.
PACKAGES = {
    ('image', '0.25.10'), ('base64', '0.22.1'), ('futures', '0.3.34'), ('futures-executor', '0.3.34'), ('pastey', '0.2.3'),
    ('rmcp', '3.8.0'), ('rmcp-macros', '3.8.0'), ('schemars_derive', '1.2.3'),
    ('serde_derive_internals', '0.30.0'), ('percent-encoding', '2.3.2'),
    ('async-trait','0.1.92'), ('axum','0.8.9'), ('axum-core','0.5.6'), ('chacha20','0.10.2'), ('cpufeatures','0.3.1'),
    ('httpdate','1.0.3'), ('matchit','0.8.4'), ('rand','0.10.3'), ('rand_core','0.10.1'),
    ('sse-stream','0.2.6'), ('tokio-stream','0.1.19'),
}


def metadata(features, host):
    result = subprocess.run([
        'cargo', 'metadata', '--locked', '--offline', '--format-version', '1',
        '--manifest-path', str(ROOT / 'src-tauri/Cargo.toml'),
        '--filter-platform', host, '--features', features,
    ], check=True, capture_output=True, text=True, encoding='utf-8', timeout=120)
    return json.loads(result.stdout)


def render(host=None):
    if host is None:
        version = subprocess.run(['rustc', '-vV'], check=True, capture_output=True,
                                 text=True, timeout=15).stdout
        host = next(line.removeprefix('host: ') for line in version.splitlines() if line.startswith('host: '))
    full = metadata('desktop,mcp', host)
    nodes = {node['id']: node for node in full['resolve']['nodes']}
    active = set(nodes)
    root = full['resolve']['root']
    # desktop now includes mcp, so compare the active MCP roots against the
    # ordinary desktop dependency closure instead of two identical feature sets.
    ordinary = [dep['pkg'] for dep in nodes[root]['deps']
                if dep['name'] not in {'rmcp', 'axum', 'percent_encoding', 'tokio_util'}]
    base = set()
    while ordinary:
        package = ordinary.pop()
        if package in base:
            continue
        base.add(package)
        ordinary.extend(dep['pkg'] for dep in nodes[package]['deps'])
    additions = active - base - {root}
    by_id = {package['id']: package for package in full['packages']}
    missing = {(by_id[key]['name'], by_id[key]['version']) for key in additions} - PACKAGES
    if missing:
        raise ValueError(f'MCP dependency license review required: {sorted(missing)}')
    packages = {(p['name'], p['version']): p for p in full['packages'] if p['id'] in active}
    # One notice file covers all supported builds. ARM excludes x86-only crates
    # such as cpufeatures 0.3, whose complete notices must still be retained.
    canonical = 'x86_64-pc-windows-msvc'
    if PACKAGES - packages.keys() and host != canonical:
        for package in metadata('desktop,mcp', canonical)['packages']:
            packages.setdefault((package['name'], package['version']), package)
    unavailable = PACKAGES - packages.keys()
    if unavailable:
        raise ValueError(f'Missing MCP license sources: {sorted(unavailable)}; '
                         'run cargo fetch --locked --manifest-path src-tauri/Cargo.toml '
                         '--target x86_64-pc-windows-msvc')
    parts = ['Third-party licenses for the local MCP Streamable HTTP service\n\n'
             'Generated by scripts/update_mcp_licenses.py from locked Cargo packages.\n'
             'These are the MCP additions to the existing desktop dependency graph,\n'
             'including HTTP transport, build-time macros, URI decoding, image previews and Base64 encoding.\n'
             'Full upstream license files are retained, including dual-license texts.\n\n']
    for key in sorted(PACKAGES):
        package = packages[key]
        directory = Path(package['manifest_path']).parent
        files = sorted(file for file in directory.iterdir() if file.is_file()
                       and file.name.upper().startswith(('LICENSE', 'LICENCE', 'COPYING', 'NOTICE', 'COPYRIGHT')))
        if not files:
            raise ValueError(f'Missing upstream license text: {key}')
        parts.append(f'{key[0]} {key[1]} ({package["license"]})\nhttps://crates.io/crates/{key[0]}/{key[1]}\n')
        for file in files:
            parts.append(f'\n--- {file.name} ---\n{file.read_text(encoding="utf-8").rstrip()}\n')
        parts.append('\n' + '=' * 72 + '\n\n')
    return ''.join(parts)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = render()
    target = ROOT / 'vendor/mcp-licenses.txt'
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != content:
            parser.exit(1, 'MCP licenses differ; review dependencies and run scripts/update_mcp_licenses.py\n')
    else:
        target.write_text(content, encoding='utf-8', newline='\n')
    print(f'MCP licenses: {"verified" if args.check else "updated"} ({len(PACKAGES)} packages)')
