async page => {
  const browser = await page.context().browser().browserType().connectOverCDP('http://127.0.0.1:9340');
  const p = browser.contexts()[0].pages().find(p => p.url() === 'http://127.0.0.1:1420/');
  if (!p) throw Error('native acceptance page missing');
  p.setDefaultTimeout(15000);
  const invoke = (command, args = {}) => p.evaluate(({ command, args }) => window.__TAURI_INTERNALS__.invoke(command, args), { command, args });
  const check = (value, text) => { if (!value) throw Error(text); };
  check((await invoke('get_settings')).download_directory.includes('wb310-final'), 'wrong profile');
  await p.getByRole('button', { name: '系统设置', exact: true }).click();
  await p.getByRole('navigation', { name: '设置分类' }).getByRole('button', { name: 'MCP', exact: true }).click();
  const panel = p.locator('.mcp-settings');
  const service = panel.getByRole('switch', { name: '启用 MCP' });
  const writing = panel.getByRole('switch', { name: '允许 AI 写入' });
  await panel.getByText('已关闭', { exact: true }).waitFor();
  check(await writing.isDisabled(), 'native off service allowed write authorization');
  await service.click(); await panel.getByText('运行中', { exact: true }).waitFor();
  check(!(await invoke('get_mcp_connection')).write_enabled, 'native service implicitly granted write');
  await writing.focus(); await p.keyboard.press('Space'); await panel.getByText('已允许写入', { exact: true }).waitFor();
  check((await invoke('get_mcp_connection')).write_enabled, 'native toggle did not authorize Core');
  await panel.getByRole('button', { name: '复制地址', exact: true }).click(); await panel.getByText('地址已复制', { exact: true }).waitFor();
  await p.screenshot({ path: '.local/wb310/native-writing-settings.png', fullPage: true });
  await writing.click(); await panel.getByText('仅允许读取', { exact: true }).waitFor();
  check(!(await invoke('get_mcp_connection')).write_enabled, 'native toggle failed to revoke');
  await writing.click(); await panel.getByText('已允许写入', { exact: true }).waitFor();
  await service.click(); await panel.getByText('已关闭', { exact: true }).waitFor();
  check(!(await invoke('get_mcp_connection')).write_enabled, 'native service stop retained permission');
  await p.getByRole('button', { name: '工作台', exact: true }).click();
  await p.getByRole('button', { name: '选题与草稿', exact: true }).click();
  const ideas = p.getByRole('region', { name: '选题与草稿', exact: true });
  await ideas.getByRole('button', { name: 'WB310 原生草稿😀', exact: true }).click();
  await ideas.getByText('AI 创建', { exact: true }).waitFor();
  await ideas.locator('summary').filter({ hasText: 'wb310-native-synthetic-model' }).click();
  check(await ideas.getByRole('textbox', { name: '自己的草稿', exact: true }).inputValue() === '独立创作正文', 'native AI draft content missing');
  await p.screenshot({ path: '.local/wb310/native-writing-idea.png', fullPage: true });
  await ideas.getByRole('button', { name: '返回知识库', exact: true }).click();
  await p.getByRole('button', { name: '研究专题', exact: true }).click();
  const topics = p.getByRole('region', { name: '研究专题', exact: true });
  await topics.getByRole('button', { name: 'WB310 原生研究😀', exact: true }).click();
  await topics.getByText('AI 创建', { exact: true }).waitFor();
  await topics.locator('summary').filter({ hasText: 'wb310-native-synthetic-model' }).click();
  check(await topics.getByRole('textbox', { name: '专题研究内容', exact: true }).inputValue() === '基于固定文案引用', 'native topic missing');
  await invoke('set_mcp_service_enabled', { enabled: true });
  await invoke('set_mcp_write_enabled', { enabled: true });
  check((await invoke('get_mcp_connection')).write_enabled, 'failed to arm restart authorization check');
  return [{ nativeWriteToggleKeyboardClipboardAndServiceReset: 'PASS' }, { nativeMcpCreatedDraftAndTopicProvenance: 'PASS' }];
}
