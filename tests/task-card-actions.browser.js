// Isolated app/clipboard mocks; never starts the actual system player.
async page => {
  page.setDefaultTimeout(8000);
  const base=page.url().split('/').slice(0,3).join('/');
  const check=(ok,message)=>{if(!ok)throw Error(message)};
  const row=id=>page.locator('[data-task-id="visual-'+id+'"]');
  const results=[];
  const load=async()=>{
    await page.evaluate(()=>localStorage.removeItem('yingqu.task-view'));
    await page.goto(base+'/tests/fixtures/background-download.html?scenario=visual-list');
    await page.getByRole('button',{name:'下载任务',exact:true}).click();
    await page.getByRole('button',{name:'切换为信息流',exact:true}).click();
  };
  for(const [width,height] of [[1440,900],[1280,800],[1024,680]]){
    await page.setViewportSize({width,height});await load();
    const cover=row(1).getByRole('button',{name:'查看封面',exact:true});
    check(await cover.isDisabled(),'downloading cover is enabled');
    await row(1).hover();
    check(await cover.evaluate(n=>getComputedStyle(n).opacity==='1'&&getComputedStyle(n.querySelector('img')).opacity==='0.25'&&getComputedStyle(n.querySelector('img')).transform==='none'),'disabled cover appearance or hover zoom');
    await cover.dispatchEvent('click');
    check(await page.getByRole('dialog').count()===0,'downloading cover opened details');
    check(await row(1).getByRole('progressbar',{name:'下载进度',exact:true}).count()===1 && await row(1).locator('.task-row-footer').count()===0,'progress missing or downloading footer remains');
    const error=row(4).getByRole('alert');
    check(await error.count()===1 && await error.evaluate(n=>n.parentElement.classList.contains('task-row-cover')),'error is not exclusively inside cover');
    const eb=await error.boundingBox(),cb=await row(4).locator('.task-row-cover').boundingBox();
    check(eb.y>=cb.y && eb.y<cb.y+20 && eb.x>=cb.x && eb.x+eb.width<=cb.x+cb.width,'error placement escaped cover top');
    const gallery=row(6).getByRole('button',{name:'查看图集',exact:true});
    check(await gallery.count()===1 && await gallery.locator('svg.lucide-images').count()===1,'gallery icon missing or duplicated');
    check(await row(6).locator('.task-row-footer button').count()===0,'footer gallery action remains');
    const gb=await gallery.boundingBox(),ab=await row(6).locator('.task-row-cover').boundingBox();
    check(gb.y<ab.y+12 && gb.x+gb.width>ab.x+ab.width-12,'gallery icon is not top right');
    await gallery.focus();await page.keyboard.press('Enter');
    const dialog=page.getByRole('dialog',{name:'街角光影，城市漫游图集',exact:true});await dialog.waitFor();
    check(await dialog.locator('.album-thumbnail').count()===2,'gallery viewer lost images');
    await page.keyboard.press('Escape');await dialog.waitFor({state:'detached'});
    await page.evaluate(()=>{
      window.copiedTaskPaths=[];
      Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.copiedTaskPaths.push(text)}}});
    });
    await row(3).locator('.task-row-title').click({button:'right'});
    const menu=page.getByRole('menu',{name:'任务操作',exact:true});await menu.waitFor();
    const names=await menu.getByRole('menuitem').allTextContents();
    check(names.indexOf('复制本地地址')===names.indexOf('复制原链接')+1,'local address is not immediately below original URL');
    await menu.getByRole('menuitem',{name:'复制本地地址',exact:true}).click();
    check(await page.evaluate(()=>window.copiedTaskPaths[0]===window.backgroundTest.snapshot().find(t=>t.id==='visual-3').path),'clipboard did not receive full absolute local path');
    await page.locator('[data-sonner-toast]').filter({hasText:'本地地址已复制'}).waitFor();
    await row(6).locator('.task-row-title').click({button:'right'});await menu.waitFor();
    check(await menu.getByRole('menuitem',{name:'复制本地地址',exact:true}).count()===0,'album exposes copy local video path');
    await page.keyboard.press('Escape');await menu.waitFor({state:'detached'});
    await page.evaluate(async()=>{
      const {api}=await import(performance.getEntriesByType('resource').find(e=>e.name.includes('/src/api.ts')).name);
      window.cardPlayCalls=[];
      api.playbackSource=async id=>{window.cardPlayCalls.push(id);return await new Promise(resolve=>window.releaseCardPlay=()=>resolve('/tests/fixtures/media/player.webm'))};
      window.otherButtonChanges=[];
      window.cardButtonObserver=new MutationObserver(records=>window.otherButtonChanges.push(...records.map(r=>r.target.closest('[data-task-id]')?.dataset.taskId)));
      for(const n of document.querySelectorAll('[data-task-id]:not([data-task-id="visual-3"]) button'))window.cardButtonObserver.observe(n,{attributes:true,attributeFilter:['disabled','aria-busy']});
    });
    const play=row(3).locator('.task-play');
    await play.click();
    check(await play.isDisabled() && await page.locator('.video-player-loading').isVisible(),'current play has no local loading feedback');
    check(await row(9).locator('.task-play').isEnabled(),'other video was globally disabled');
    check(await row(2).getByRole('button',{name:'取消',exact:true,includeHidden:true}).isEnabled(),'unrelated task action was globally disabled');
    await row(3).locator('.task-row-title').dispatchEvent('dblclick');
    check(await page.evaluate(()=>window.cardPlayCalls.length===1 && window.otherButtonChanges.length===0),'duplicate playback or other buttons flickered');
    await page.evaluate(()=>window.releaseCardPlay());
    await page.waitForFunction(()=>document.querySelector('.video-player-dialog video')?.readyState>=2);
    await page.keyboard.press('Escape');await page.locator('.video-player-dialog').waitFor({state:'detached'});
    await page.waitForFunction(()=>!document.querySelector('[data-task-id="visual-3"] .task-play').disabled);
    check(await page.evaluate(()=>window.otherButtonChanges.length===0),'play completion flickered other buttons');
    await page.evaluate(()=>window.cardButtonObserver.disconnect());
    await page.screenshot({path:`.local/task-paging/cards-${width}.png`});
    results.push(`${width}: disabled cover, top error, top-right gallery/keyboard, absolute path clipboard, play busy isolation/deduplication`);
  }
  await load();
  await page.evaluate(async()=>{
    const {api}=await import(performance.getEntriesByType('resource').find(e=>e.name.includes('/src/api.ts')).name);
    api.playbackSource=async()=>{throw 'PLAYBACK_SOURCE_FAILED'};
    api.play=async()=>{throw 'PLAYBACK_OPEN_FAILED'};
    Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw 'CLIPBOARD_WRITE_FAILED'}}});
  });
  await row(3).getByRole('button',{name:'播放视频',exact:true}).click();
  await page.locator('[data-sonner-toast][data-type="error"]').filter({hasText:'无法启动系统默认播放器'}).waitFor();
  check(await row(9).locator('.task-play').isEnabled(),'play failure left other buttons disabled');
  await page.keyboard.press('Escape');await page.locator('.video-player-dialog').waitFor({state:'detached'});
  await row(3).locator('.task-row-title').click({button:'right'});
  await page.getByRole('menuitem',{name:'复制本地地址',exact:true}).click();
  await page.locator('[data-sonner-toast][data-type="error"]').filter({hasText:'操作失败'}).waitFor();
  await page.evaluate(()=>window.backgroundTest.complete('visual-1'));
  await page.waitForFunction(()=>!document.querySelector('[data-task-id="visual-1"] [data-media-cover]').disabled);
  await row(1).getByRole('button',{name:'查看封面',exact:true}).click();
  await page.getByRole('dialog',{name:'任务详情',exact:true}).waitFor();
  results.push('play and clipboard failures remain visible; completed cover re-enables details');
  await page.keyboard.press('Escape');await page.getByRole('dialog').waitFor({state:'detached'});
  await load();
  await row(1).locator('.task-row-title').click({button:'right'});
  await page.getByRole('menuitem',{name:'取消下载',exact:true}).click();
  const cancelDialog=page.getByRole('alertdialog',{name:'取消当前任务？',exact:true});
  await cancelDialog.waitFor();await cancelDialog.getByRole('button',{name:'返回',exact:true}).click();
  await cancelDialog.waitFor({state:'detached'});
  check(await page.evaluate(()=>!window.backgroundTest.calls.some(c=>c.type==='cancel')),'back action canceled download');
  await page.waitForFunction(()=>document.activeElement?.closest('[data-task-row]')?.dataset.taskRow==='visual-1');
  await page.keyboard.press('Shift+F10');
  await page.getByRole('menuitem',{name:'取消下载',exact:true}).click();await cancelDialog.waitFor();
  await cancelDialog.getByRole('button',{name:'确认取消',exact:true}).click();
  await cancelDialog.waitFor({state:'detached'});
  await page.waitForFunction(()=>window.backgroundTest.calls.some(c=>c.type==='cancel'&&c.id==='visual-1'));
  check(await row(1).getAttribute('data-status')==='canceled','menu cancellation did not update task');
  await load();
  await page.getByRole('button',{name:'切换为列表',exact:true}).click();
  check(await row(1).getByRole('button',{name:'取消',exact:true}).isEnabled() && await row(1).locator('.task-row-status').innerText()==='下载中','list download controls changed');
  results.push('feed cancellation via menu/confirmation/back/keyboard focus; list status and cancel retained');
  return {passed:results.length,results};
}
