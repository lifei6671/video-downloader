// Existing Playwright CLI; production React with isolated native IPC fixtures.
async page => {
  page.setDefaultTimeout(8000);
  const check = (ok, message) => { if (!ok) throw Error(message); };
  const results = [];
  const detail = () => page.getByRole('region', { name: '视频资料详情', exact: true });
  const ready = () => page.waitForFunction(() => document.querySelector('.library-asset-detail')?.getAttribute('aria-busy') === 'false');
  const load = async () => { await page.goto('http://127.0.0.1:1420/tests/fixtures/knowledge-library.html?detail=1'); await page.getByRole('button', { name: '素材库', exact: true }).click(); await page.waitForFunction(() => document.querySelector('.library-list')?.getAttribute('aria-busy') === 'false'); };
  const open = async (id, keyboard = false) => { const trigger = page.locator('[data-library-asset="' + id + '"]').getByRole('button', { name: /^查看视频资料/ }); if (keyboard) { await trigger.focus(); await page.keyboard.press('Enter'); } else await trigger.click(); await ready(); };
  const field = name => detail().locator('dt').filter({ hasText: new RegExp('^' + name + '$') }).locator('+ dd');
  for (const [width, height] of [[1440, 900], [1280, 800], [1024, 680]]) {
    await page.setViewportSize({ width, height }); await load(); await open('a0', true);
    check(await field('作者').innerText() === '作者未知', 'unknown author fabricated');
    check(await field('分辨率').innerText() === '160 × 90', 'file dimensions missing');
    const expected = await page.evaluate(() => new Date(1793000000 * 1000).toLocaleString('zh-CN'));
    check(await field('收录时间').innerText() === expected && expected.includes('2026'), 'UTC seconds rendered as milliseconds');
    check((await field('文件路径').innerText()).length > 260, 'long Unicode path missing');
    const media = await detail().locator('.library-detail-media').boundingBox();
    const info = await detail().locator('.library-detail-information').boundingBox();
    check(width === 1024 ? info.y > media.y + media.height : info.x > media.x + media.width - 1, 'responsive columns wrong');
    check(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), 'horizontal overflow ' + width);
    check(await detail().getByRole('combobox', { name: '文件版本' }).count() === 0, 'file versions remain visible');
    check(await detail().getByText('版本与笔记摘要', { exact: true }).count() === 0, 'note summaries remain visible');
    check(await detail().getByRole('heading', { name: '关键帧', exact: true }).count() === 0, 'keyframes remain visible');
    check(await detail().locator('.library-detail-information section').count() === 1, 'right column contains non-writing sections');
    check(await detail().locator('.library-detail-media .library-detail-labels').count() === 1, 'labels are not below video');
    await page.screenshot({ path: '.local/wb114-detail-' + width + '.png', animations: 'disabled' });
    await detail().getByRole('heading', { level: 2 }).focus(); await page.keyboard.press('Control+End');
    await page.waitForFunction(() => { const node = document.querySelector('.library-asset-detail'); return node.scrollHeight - node.clientHeight - node.scrollTop < 2; });
    check(await page.evaluate(() => document.documentElement.scrollTop === 0), 'detail introduced outer document scrolling');
    await page.screenshot({ path: '.local/wb114-detail-bottom-' + width + '.png', animations: 'disabled' });
    await detail().getByRole('button', { name: '复制来源链接', exact: true }).click();
    check(await page.evaluate(() => window.libraryDetailTest.calls.some(call => call.method === 'copy' && call.text === 'https://example.invalid/video/source-a0')), 'copy source wrong');
    await detail().getByRole('button', { name: '定位文件', exact: true }).click();
    await page.waitForFunction(() => window.libraryDetailTest.calls.some(call => call.method === 'reveal' && call.assetId === 'a0' && call.fileId === 'f-a0'));
    await detail().getByRole('button', { name: '修改', exact: true }).click();
    await page.getByRole('dialog').getByRole('checkbox', { name: '拍摄手法', exact: true }).check();
    await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' }); await ready();
    await detail().locator('.library-detail-labels').getByText('拍摄手法', { exact: true }).waitFor();
    await detail().getByRole('button', { name: '返回列表', exact: true }).click();
    await detail().waitFor({ state: 'hidden' });
    await page.waitForFunction(() => document.activeElement?.classList.contains('library-asset-title'));
    results.push(width + ': responsive detail/Unicode path/seconds timestamp/metadata/no versions/labels below video/copy/location/memberships/back focus');
  }
  await load(); await open('a2');
  check(await detail().getByRole('button', { name: '播放视频', exact: true }).isDisabled(), 'missing file can play');
  check(await detail().getByRole('button', { name: '系统播放器', exact: true }).isDisabled(), 'missing external launch enabled');
  check(await detail().getByRole('textbox', { name: '原始文案内容' }).isVisible(), 'missing file hides retained transcript');
  const original = await page.evaluate(() => window.libraryDetailTest.snapshot('a2'));
  await page.evaluate(() => window.libraryDetailTest.relinkMode('cancel'));
  await detail().getByRole('button', { name: '重新关联文件', exact: true }).click();
  await detail().getByRole('button', { name: '重新关联文件', exact: true }).waitFor();
  check(await page.evaluate(() => window.libraryDetailTest.snapshot('a2').files[0].path) === original.files[0].path, 'picker cancel changed source');
  await page.evaluate(() => window.libraryDetailTest.relinkMode('failure'));
  await detail().getByRole('button', { name: '重新关联文件', exact: true }).click();
  await detail().getByRole('alert').filter({ hasText: '无法读取有效视频' }).waitFor();
  check(await page.evaluate(() => window.libraryDetailTest.snapshot('a2').files[0].path) === original.files[0].path, 'bad replacement changed source');
  await page.evaluate(() => window.libraryDetailTest.relinkMode('hold'));
  await detail().getByRole('button', { name: '重新关联文件', exact: true }).click();
  await detail().getByRole('button', { name: '取消关联', exact: true }).click();
  await detail().getByRole('button', { name: '重新关联文件', exact: true }).waitFor();
  check(await detail().getByRole('alert').count() === 0, 'operation cancellation shown as failure');
  await page.evaluate(() => window.libraryDetailTest.relinkMode('success'));
  await detail().getByRole('button', { name: '重新关联文件', exact: true }).click(); await ready();
  await page.waitForFunction(() => document.querySelector('.library-detail-fields dd')?.textContent.includes('重新关联.mp4'));
  check(!await detail().getByRole('button', { name: '播放视频', exact: true }).isDisabled(), 'relink did not restore playback');
  check(await page.evaluate(() => { const d = window.libraryDetailTest.snapshot('a2'); return d.files[0].id === 'f-a2' && d.documents[0].id === 'd-a2' && d.notes[0].id === 'n-a2'; }), 'relink changed stable IDs or lost materials');
  results.push('missing file retains materials; relink picker cancel/failure/operation cancel/success and stable IDs');

  await load(); await open('a3');
  await detail().getByText('文件已变化', { exact: true }).waitFor();
  await detail().getByText('文件已变化，以下规格为登记时信息。', { exact: true }).waitFor();
  await detail().getByRole('button', { name: '返回列表', exact: true }).click(); await open('a4');
  check(await field('时长').innerText() === '未知' && await field('分辨率').innerText() === '未知', 'unknown file metadata fabricated');
  await detail().getByRole('button', { name: '返回列表', exact: true }).click(); await open('a5');
  await detail().getByText('暂无关联文件', { exact: true }).waitFor();
  check(await detail().getByRole('button', { name: '播放视频', exact: true }).count() === 0, 'no-file asset got imaginary playback');
  check(await detail().getByRole('textbox', { name: '原始文案内容' }).isVisible(), 'no-file asset lost saved text');
  results.push('changed/unknown/no-file states keep source and document summaries');

  await load(); await open('a0'); await page.evaluate(() => window.libraryDetailTest.fail('detail'));
  await detail().getByRole('button', { name: '刷新视频资料' }).click(); await ready();
  await detail().getByRole('alert').waitFor();
  await detail().getByRole('button', { name: '重新读取资料', exact: true }).click(); await ready();
  check(await detail().getByRole('alert').count() === 0, 'detail retry did not clear failure');
  await page.evaluate(() => window.libraryDetailTest.fail('open'));
  await detail().getByRole('button', { name: '系统播放器', exact: true }).click();
  await detail().getByRole('alert').filter({ hasText: '无法启动系统默认播放器' }).waitFor();
  results.push('detail read retry and native launch failures remain visible');
  return { passed: results.length, cases: results };
}
