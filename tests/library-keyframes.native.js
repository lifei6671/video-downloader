// Production IPC and WebView2; only the marked synthetic WB304 profile.
async page => {
  const browser = await page.context().browser().browserType().connectOverCDP('http://127.0.0.1:9334');
  const p = browser.contexts()[0].pages().find(p => p.url() === 'http://127.0.0.1:1420/');
  if (!p) throw Error('WB304 WebView2 not found');
  p.setDefaultTimeout(15000);
  const check = (ok, message) => { if (!ok) throw Error(message); }, results = [];
  const invoke = (command, args = {}) => p.evaluate(({ command, args }) => window.__TAURI_INTERNALS__.invoke(command, args), { command, args });
  check((await invoke('get_settings')).download_directory.includes('wb304-final'), 'unmarked profile');
  const assets = await invoke('search_library_assets', { request: {} });
  const assetId = assets.items.find(row => row.asset.video_id === '7300000000000000001').asset.id;
  for (const row of await invoke('list_library_clips', { assetId })) await invoke('delete_library_clip', { assetId, clipId: row.id });
  for (const row of await invoke('list_library_keyframes', { assetId })) await invoke('delete_library_keyframe', { assetId, keyframeId: row.id });
  const data = await invoke('get_library_asset', { assetId });
  const original = data.files.find(f => f.path.endsWith('原视频.mp4')), special = data.files.find(f => f.path.endsWith('另一个版本.mp4'));
  await p.getByRole('button', { name: '知识库', exact: true }).click();
  const detail = p.getByRole('region', { name: '视频资料详情', exact: true });
  if (await detail.isVisible()) await detail.getByRole('button', { name: '返回列表', exact: true }).click();
  await p.locator('[data-library-asset="' + assetId + '"]').getByRole('button', { name: /^查看视频资料/ }).click();
  const frames = p.getByRole('region', { name: '关键帧', exact: true });
  const choose = async filename => { await detail.getByRole('combobox', { name: '文件版本', exact: true }).click(); await p.getByRole('option').filter({ hasText: filename }).click(); };
  const capture = async (filename, seconds) => {
    const previous = await invoke('get_library_keyframe_operation');
    await choose(filename); await detail.getByRole('button', { name: '播放视频', exact: true }).click();
    await p.waitForFunction(() => document.querySelector('video')?.readyState >= 2);
    await detail.locator('video').evaluate((v, time) => { v.pause(); v.currentTime = time; }, seconds);
    await p.waitForFunction(() => !document.querySelector('video').seeking);
    await frames.getByRole('button', { name: '当前位置取帧', exact: true }).click();
    await p.waitForFunction(async id => { const op = await window.__TAURI_INTERNALS__.invoke('get_library_keyframe_operation'); return op && op.id !== id && op.state === 'completed'; }, previous?.id ?? null);
    await frames.getByText('已保存 1 张关键帧', { exact: true }).waitFor();
  };
  await capture('原视频.mp4', .35);
  let rows = await invoke('list_library_keyframes', { assetId });
  check(rows.length === 1 && rows[0].requested_ms === 350 && rows[0].actual_ms === 400, 'normal PTS');
  await p.waitForFunction(() => document.querySelector('.library-frame-image img')?.naturalHeight === 160);
  const binary = await p.evaluate(async args => { const b = await window.__TAURI_INTERNALS__.invoke('get_library_keyframe_image', args); return b instanceof ArrayBuffer && new Uint8Array(b)[0] === 137; }, { assetId, keyframeId: rows[0].id });
  check(binary, 'binary PNG IPC');
  await frames.getByRole('button', { name: /^查看关键帧/ }).click();
  await p.getByRole('dialog').getByRole('img', { name: /^关键帧 / }).waitFor(); await p.keyboard.press('Escape');
  results.push('native clock 350ms -> actual PTS 400ms; binary PNG IPC and decoded portrait; preview/Escape');
  const clipId = await invoke('create_library_clip', { assetId, input: { file_id: original.id, title: '原生关键帧片段', reason: '', start_ms: 500, end_ms: 1250, playable: { start_ms: 0, end_ms: 1500 }, document_id: null, quote: null } });
  await detail.getByRole('button', { name: '提取关键帧 原生关键帧片段', exact: true }).click();
  await p.getByRole('menuitem', { name: '提取 3 帧', exact: true }).click();
  await frames.getByText('已保存 3 张关键帧', { exact: true }).waitFor();
  rows = await invoke('list_library_keyframes', { assetId });
  const sampled = rows.filter(f => f.clip_id === clipId).sort((a, b) => a.sample_index - b.sample_index);
  check(JSON.stringify(sampled.map(f => [f.requested_ms, f.actual_ms])) === '[[625,700],[875,900],[1125,1200]]', 'clip sampling');
  await capture('另一个版本.mp4', 5.35);
  rows = await invoke('list_library_keyframes', { assetId });
  check(rows.some(f => f.file_id === special.id && f.requested_ms === 5350 && f.actual_ms === 5400 && f.black), 'positive PTS / black frame');
  results.push('native clip dropdown: 625/875/1125 -> 700/900/1200ms; positive-start MP4 5350 -> 5400ms, black frame retained');
  const before = rows.length;
  await invoke('start_library_keyframes', { assetId, request: { kind: 'position', file_id: special.id, position_ms: 200 } });
  await frames.getByRole('alert').filter({ hasText: '采样位置没有可用画面' }).waitFor();
  check((await invoke('list_library_keyframes', { assetId })).length === before, 'invalid range wrote images');
  const other = assets.items.find(row => row.asset.id !== assetId).asset.id;
  const failure = await p.evaluate(args => window.__TAURI_INTERNALS__.invoke('get_library_keyframe_image', args).then(() => '', reason => String(reason)), { assetId: other, keyframeId: rows[0].id });
  check(!!failure, 'foreign image readable');
  await frames.getByRole('button', { name: /^删除关键帧/ }).first().click();
  await p.waitForFunction(n => document.querySelectorAll('[data-keyframe]').length === n, before - 1);
  check((await invoke('list_library_clips', { assetId })).some(c => c.id === clipId), 'image delete removed clip');
  await frames.scrollIntoViewIfNeeded(); await p.screenshot({ path: 'output/playwright/wb304-native.png', animations: 'disabled' });
  results.push('native invalid head rejected without partial images; foreign asset read rejected; delete preserves clip');
  await browser.close();
  return { status: 'PASSED', nativeTauri: true, assetId, frameCount: before - 1, cases: results };
}
