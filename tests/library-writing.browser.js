async page => {
  page.setDefaultTimeout(10000);
  const check = (ok, message) => { if (!ok) throw Error(message); };
  const panel = () => page.getByRole('region', { name: '素材文案', exact: true });
  const ready = () => page.waitForFunction(() => document.querySelector('.library-writing')?.getAttribute('aria-busy') === 'false');
  await page.goto('http://127.0.0.1:1420/tests/fixtures/knowledge-library.html?detail=1&writing=1');
  await page.getByRole('button', { name: '素材库', exact: true }).click();
  await page.locator('[data-library-asset="a0"] .library-asset-title').click(); await ready();
  check(await panel().getByRole('tab').count() === 2, 'detail must have two writing tabs');
  check(await panel().getByRole('textbox', { name: '原始文案内容' }).isEditable(), 'original text not editable');
  const draft = '人工校正的原始文案😀\n第二段';
  await panel().getByRole('textbox', { name: '原始文案内容' }).fill(draft);
  await panel().getByRole('button', { name: '保存', exact: true }).click();
  await panel().getByRole('button', { name: '保存', exact: true, disabled: true }).waitFor();
  check(await page.evaluate(() => window.writingTest.snapshot('a0').documents.some(d => d.summary.kind === 'recognized' && d.text.startsWith('中文原文'))), 'recognition evidence lost');
  check(await page.evaluate(text => window.writingTest.snapshot('a0').documents.some(d => d.summary.kind === 'edited' && d.text === text && d.summary.source_document_id === 'd-a0'), draft), 'correction not saved with source');
  await panel().getByRole('tab', { name: 'AI 总结', exact: true }).click(); await ready();
  check(await panel().getByRole('textbox', { name: 'AI 总结内容' }).inputValue() === '', 'ordinary note mislabeled as AI summary');
  await panel().getByRole('combobox', { name: '选择总结内容', exact: true }).click();
  await page.getByRole('option', { name: '历史内容 1', exact: true }).click(); await ready();
  check(await panel().getByRole('textbox', { name: 'AI 总结内容' }).inputValue() === '已保存学习笔记', 'single historical note became inaccessible');
  await panel().getByRole('tab', { name: '原始文案', exact: true }).click(); await ready();
  await panel().getByRole('tab', { name: 'AI 总结', exact: true }).click(); await ready();
  const markdown = '# 写作手法\n\n**先提出问题**，再举例。\n\n- 表达：短句递进\n- 分镜：近景切换\n\n<script>window.summaryUnsafe=true</script>\n\n![remote](https://example.invalid/tracker.png)';
  await panel().getByRole('textbox', { name: 'AI 总结内容' }).fill(markdown);
  await panel().getByRole('button', { name: '预览', exact: true }).click();
  await panel().getByRole('heading', { name: '写作手法', exact: true }).waitFor();
  check(await panel().locator('.library-summary-preview strong').innerText() === '先提出问题', 'Markdown bold not rendered');
  check(await panel().locator('.library-summary-preview img, .library-summary-preview script').count() === 0, 'preview loaded active or remote content');
  await panel().getByRole('button', { name: '保存', exact: true }).click();
  await panel().getByRole('button', { name: '保存', exact: true, disabled: true }).waitFor();
  await page.getByRole('button', { name: '返回列表', exact: true }).click();
  await page.locator('[data-library-asset="a0"] .library-asset-title').click(); await ready();
  check(await panel().getByRole('textbox', { name: '原始文案内容' }).inputValue() === draft, 'correction lost on reentry');
  await panel().getByRole('tab', { name: 'AI 总结', exact: true }).click(); await ready();
  check(await panel().getByRole('textbox', { name: 'AI 总结内容' }).inputValue() === markdown, 'Markdown summary lost on reentry');
  check(await panel().getByRole('button', { name: /复制|导出/ }).count() === 0, 'copy or export remains');
  await panel().getByRole('textbox', { name: 'AI 总结内容' }).fill('未保存的总结');
  await panel().getByRole('tab', { name: '原始文案', exact: true }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: '继续编辑', exact: true }).click();
  check(await panel().getByRole('textbox', { name: 'AI 总结内容' }).inputValue() === '未保存的总结', 'tab switch lost draft');
  await page.getByRole('button', { name: '返回列表', exact: true }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: '放弃修改', exact: true }).click();
  const analysisId = await page.evaluate(async () => {
    const { libraryApi } = await import('/src/lib/library-api.ts');
    return libraryApi.createAnalysis('a0', { origin: 'ai', model_name: 'synthetic-model', citations: [], content: { kind: 'copywriting', opening: '历史 AI 开头', viewpoint: '观点递进', evidence: '原文依据', turn: '转折', ending: '结尾', takeaways: '可借鉴点' } });
  });
  await page.locator('[data-library-asset="a0"] .library-asset-title').click(); await ready();
  await panel().getByRole('tab', { name: 'AI 总结', exact: true }).click(); await ready();
  check((await panel().getByRole('textbox', { name: 'AI 总结内容' }).inputValue()).includes('历史 AI 开头'), 'historical AI analysis unreadable');
  await panel().getByRole('textbox', { name: 'AI 总结内容' }).fill('# 重新整理的 AI 总结');
  await panel().getByRole('button', { name: '保存', exact: true }).click();
  await panel().getByRole('button', { name: '保存', exact: true, disabled: true }).waitFor();
  check(await page.evaluate(id => window.analysisTest.notes('a0').some(n => n.id === id && n.analysis.content.opening === '历史 AI 开头'), analysisId), 'legacy structured analysis was overwritten');
  check(await panel().getByRole('combobox', { name: '选择总结内容', exact: true }).isVisible(), 'multiple historical notes inaccessible');
  await page.getByRole('button', { name: '返回列表', exact: true }).click();
  await page.locator('[data-library-asset="a0"] .library-asset-title').click(); await ready();
  await panel().getByRole('tab', { name: 'AI 总结', exact: true }).click(); await ready();
  check(await panel().getByRole('textbox', { name: 'AI 总结内容' }).inputValue() === '# 重新整理的 AI 总结', 'edited summary did not reopen');
  return { passed: 1, cases: ['two tabs / editable original / source retained / Markdown preview and save / no export / navigation protection'] };
}
