async page => {
  page.setDefaultTimeout(8000);
  const check = (value, message) => { if (!value) throw Error(message); };
  const ready = () => page.waitForFunction(() => document.querySelector('.library-list')?.getAttribute('aria-busy') === 'false');
  await page.goto('http://127.0.0.1:1420/tests/fixtures/knowledge-library.html?detail=1&writing=1&materials=1', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: '下载任务', exact: true }).click();
  if (await page.getByRole('button', { name: '切换为信息流', exact: true }).isVisible()) await page.getByRole('button', { name: '切换为信息流', exact: true }).click();
  const row = page.locator('[data-task-id="task-45"]');
  const heart = row.getByRole('button', { name: '收藏', exact: true });
  await page.evaluate(() => { window.collectionCover = document.querySelector('[data-task-id="task-45"] [data-media-cover]'); });
  const rowStates = await page.locator('[data-task-id]').evaluateAll(nodes => nodes.map(n => n.getAttribute('data-selected')));
  await page.evaluate(() => window.libraryTest.holdCollection());
  await heart.click();
  await page.waitForFunction(() => document.querySelector('[data-task-id="task-45"] .task-feed-collection')?.getAttribute('aria-busy') === 'true');
  check(await page.locator('[data-task-id]').evaluateAll((nodes, before) => nodes.every((n, i) => n.getAttribute('data-selected') === before[i]), rowStates), 'heart changed whole-card selection');
  check(!await page.locator('[data-task-id="task-44"]').getByRole('button', { name: '播放视频', exact: true }).isDisabled(), 'collection disabled another card');
  check(await heart.evaluate(node => getComputedStyle(node).opacity) === '1', 'pending collection dims the heart');
  check(await page.evaluate(() => window.collectionCover === document.querySelector('[data-task-id="task-45"] [data-media-cover]')), 'collection remounted cover');
  await page.evaluate(() => window.libraryTest.releaseCollection());
  const red = row.getByRole('button', { name: '取消收藏', exact: true });
  await red.waitFor();
  check(await red.getAttribute('aria-pressed') === 'true', 'heart has no pressed state');
  check(await red.locator('svg').getAttribute('fill') === 'currentColor', 'heart not filled');
  check(await red.innerText() === '', 'card collection is not icon-only');
  check(await red.evaluate(node => getComputedStyle(node).color === getComputedStyle(document.documentElement).getPropertyValue('--red-11').trim() || getComputedStyle(node).color === 'rgb(206, 44, 49)'), 'heart not red');
  check(await page.evaluate(() => window.libraryTest.snapshot().assets.find(a => a.id === 'a45').archived_at === null), 'collection not persisted');
  check(await page.evaluate(() => window.libraryTest.calls.filter(c => c.method === 'collectionBatch').every(c => c.ids.length === 2)), 'collection read was not batched');
  await red.focus(); await page.keyboard.press('Space');
  await row.getByRole('button', { name: '收藏', exact: true }).waitFor();
  check(await page.evaluate(() => window.libraryTest.snapshot().assets.find(a => a.id === 'a45').archived_at !== null), 'keyboard toggle did not remove');
  await row.getByRole('button', { name: '收藏', exact: true }).click();
  await row.getByRole('button', { name: '取消收藏', exact: true }).waitFor();
  await page.getByRole('button', { name: '素材库', exact: true }).click(); await ready();
  await page.getByRole('textbox', { name: '搜索素材库', exact: true }).fill('灵感视频 45');
  await page.getByRole('button', { name: '搜索', exact: true }).click(); await ready();
  check(await page.locator('[data-library-asset]').count() === 1, 'collected item not searchable');
  await page.locator('[data-library-asset="a45"] .library-asset-title').click();
  await page.getByRole('region', { name: '视频资料详情', exact: true }).waitFor();
  await page.screenshot({ path: '.local/materials-ui-followup/collected-detail.png', animations: 'disabled' });
  return { passed: 1, cases: ['icon-only heart / red fill / keyboard toggle / batched collection / detail'] };
}
