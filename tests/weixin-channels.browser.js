// Playwright CLI run-code against tests/fixtures/weixin-channels.html.
async page => {
  const fixture = page.url();
  const check = (condition, message) => { if (!condition) throw Error(message); };
  for (const [width,height] of [[1440,900],[1280,800],[1024,680]]) {
    await page.setViewportSize({width,height});
    await page.goto(fixture);
    const input = page.locator('#video-input');
    await input.fill('分享 https://weixin.qq.com/sph/Fixture');
    await page.getByRole('combobox', {name:'解析引擎'}).getByText('微信视频号').waitFor();
    await input.press('Enter');
    const progress = page.locator('[data-slot=resolve-progress]');
    await progress.getByRole('alert').getByText(/请登录腾讯元宝/).waitFor();
    const scan = progress.getByRole('button', {name:'登录腾讯元宝'});
    await scan.press('Enter');
    await page.waitForFunction(() => window.weixinTest.state().opened === 1);
    check(await scan.isDisabled(), 'scan action was not disabled while waiting');
    await page.evaluate(() => window.weixinTest.finishLogin(false));
    await scan.press('Enter');
    await page.waitForFunction(() => window.weixinTest.state().opened === 2);
    await page.evaluate(() => window.weixinTest.finishLogin(true));
    await page.getByText('已使用元宝登录', {exact:true}).waitFor();
    await progress.getByRole('button', {name:'认证设置'}).click();
    const tab = page.getByRole('tab',{name:'微信视频号',exact:true});
    check(await tab.getAttribute('aria-selected') === 'true', 'wrong settings tab');
    const form = page.locator('#profile-weixin');
    const status = form.getByRole('status').filter({hasText:'当前使用'});
    const manual = form.getByRole('tab', {name:'手动 Cookie'});
    const yuanbao = form.getByRole('tab', {name:'元宝登录'});
    check(await form.getByRole('tab').count() === 2, 'unexpected authentication tab');
    const cookie = form.getByRole('textbox',{name:'腾讯元宝网页 Cookie'});
    await status.getByText('当前使用：元宝登录').waitFor();
    check(await cookie.count() === 0, 'manual input visible under Yuanbao');
    await manual.press('Enter');
    await cookie.fill('fixture=not-a-real-cookie');
    await status.getByText('当前使用：元宝登录').waitFor();
    await form.getByRole('button',{name:'保存并切换'}).click();
    await status.getByText('当前使用：手动 Cookie').waitFor();
    await yuanbao.click();
    await form.getByRole('button', {name:'切换到元宝登录'}).click();
    await status.getByText('当前使用：元宝登录').waitFor();
    await manual.click();
    check(await cookie.inputValue() === 'fixture=not-a-real-cookie', 'manual credential lost when switching');
    const cookieDisplay = () => cookie.evaluate(node => getComputedStyle(node).getPropertyValue('-webkit-text-security'));
    check(await cookieDisplay() === 'none', 'saved Cookie should be displayed as plain text');
    await form.getByRole('button',{name:'切换到手动 Cookie'}).click();
    await status.getByText('当前使用：手动 Cookie').waitFor();
    await yuanbao.click();
    await form.getByRole('button', {name:'清除会话'}).click();
    await page.waitForFunction(() => !window.weixinTest.state().connected);
    await status.getByText('当前使用：手动 Cookie').waitFor();
    check(await tab.evaluate(node => node.getBoundingClientRect().right <= innerWidth), 'account tabs overflow');
    await page.getByRole('button',{name:'下载作品',exact:true}).click();
    await progress.getByRole('button',{name:'重新解析',exact:true}).click();
    await page.getByText('视频号测试作品', {exact:true}).waitFor();
    await page.getByRole('radio',{name:/H\.265/}).press('Space');
    await page.waitForFunction(() => window.weixinTest.state().selected === 'h265');
    const state = await page.evaluate(() => window.weixinTest.state());
    check(state.opened === 2 && state.cookieSaved && state.submitted.resolver === 'weixin' && state.submitted.auth === 'manual', 'wrong platform or active authentication');
    await page.evaluate(() => window.weixinTest.queue());
    await page.getByRole('button',{name:'下载任务',exact:true}).click();
    await page.getByRole('tab',{name:'微信视频号',exact:true}).press('Enter');
    await page.getByText('视频号测试作品',{exact:true}).waitFor();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'page overflow');
  }
  return {passed:3, viewports:[1440,1280,1024]};
}
