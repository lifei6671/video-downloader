// Playwright CLI run-code against tests/fixtures/resolve-progress.html.
async page => {
  const fixture = page.url().split('?')[0];
  const input = page.locator('#video-input');
  const form = page.locator('form').filter({has:input});
  const card = page.locator('[data-slot=resolve-progress]');
  const steps = card.getByRole('list', {name:'解析步骤'});
  const check = (condition, message) => { if (!condition) throw Error(message); };
  const load = async (mode = '') => {
    await page.goto(fixture + '?mode=' + mode);
    await input.fill(mode === 'telegram' ? 'https://t.me/c/100/9' : 'https://www.douyin.com/video/123');
    await form.getByRole('button', {name:'解析链接',exact:true}).click();
  };
  const phase = name => card.locator('[data-resolve-phase='+name+']').waitFor();
  const admit = async () => {
    await phase('submitting');
    await page.waitForFunction(() => window.resolveTest.submitted());
    check(await input.isDisabled(), 'input unlocked before admission');
    await page.evaluate(() => window.resolveTest.admit());
  };
  const advance = async name => {
    await page.evaluate(name => window.resolveTest.advance(name), name);
    await phase(name);
  };
  for (const [width,height] of [[1440,900],[1280,800],[1024,680]]) {
    await page.setViewportSize({width,height});
    await load();
    await admit();
    await phase('checking_cache');
    check(await steps.getByRole('listitem').count() === 3, 'progress must stay at three steps');
    check(await steps.locator('[data-state=done]').count() === 0, 'marks future steps complete');
    await card.getByText('www.douyin.com',{exact:true}).waitFor();
    for (const name of ['starting_engine','loading_configuration','resolving_link','fetching_metadata']) await advance(name);
    await page.evaluate(() => window.resolveTest.release());
    await page.getByRole('button',{name:'下载任务',exact:true}).click();
    await page.getByRole('button',{name:'下载作品',exact:true}).click();
    await phase('fetching_metadata');
    check(await input.isDisabled(), 'input unlocked during parsing');
    check(await steps.locator('[aria-current=step]').innerText() === '01\n读取作品信息', 'wrong information step');
    await page.screenshot({path:'.local/resolve-compact/progress-'+width+'.png'});
    await advance('selecting_formats');
    check(await steps.locator('[data-state=done]').count() === 1, 'information step did not finish');
    check((await steps.locator('[aria-current=step]').innerText()).includes('整理可用规格'), 'wrong format step');
    for (const name of ['loading_preview','loading_author','finalizing']) await advance(name);
    check(await steps.getByRole('listitem').count() === 3 && await steps.locator('[data-state=done]').count() === 2, 'steps expanded or lost completed stages');
    check((await steps.locator('[aria-current=step]').innerText()).includes('准备解析结果'), 'wrong final step');
    check(await card.getByRole('progressbar').getAttribute('aria-valuetext') === '第 3 步，共 3 步', 'stage bar claims download percentage');
    check(await card.evaluate(node => node.getBoundingClientRect().right <= innerWidth && node.scrollWidth <= node.clientWidth), 'progress overflows viewport');
    check(await card.evaluate(node => node.getBoundingClientRect().height < 280), 'progress card is too tall');
    const cancel = card.getByRole('button', {name:'取消解析',exact:true});
    await cancel.focus();
    check(await cancel.evaluate(node => document.activeElement === node), 'cancel is not keyboard focusable');
    await page.evaluate(() => window.resolveTest.finish());
    await page.getByText('解析完成的测试作品',{exact:true}).waitFor();
    await card.waitFor({state:'hidden'});
    check(await input.isEnabled(), 'input locked after result');
  }
  await load('telegram');
  await admit();
  await phase('checking_link');
  await page.evaluate(() => window.resolveTest.release());
  await advance('connecting_account');
  await page.evaluate(() => window.resolveTest.reconnect());
  await card.getByText('网络连接中断，正在重连',{exact:true}).waitFor();
  check(await card.getByRole('alert').count() === 0, 'transient reconnect shown as failure');
  await advance('fetching_metadata');
  await advance('loading_preview');
  check(await steps.locator('[data-resolve-step="1"]').getAttribute('data-state') === 'pending', 'skipped Telegram formats claimed complete');
  await page.evaluate(() => window.resolveTest.fail());
  await card.getByText('解析失败',{exact:true}).waitFor();
  await card.getByRole('alert').waitFor();
  await phase('loading_preview');
  check(await card.locator('[data-slot=spinner]').count() === 0, 'spinner keeps running after failure');
  check(await input.isEnabled(), 'input locked after failure');
  await input.fill('https://www.youtube.com/watch?v=test1234567');
  await card.getByText('t.me',{exact:true}).waitFor();
  check(await card.getByText('www.youtube.com',{exact:true}).count() === 0, 'editing input changed the failed attempt source');
  await load();
  await admit();
  await phase('checking_cache');
  await page.evaluate(() => window.resolveTest.release());
  await advance('fetching_metadata');
  await card.getByRole('button', {name:'取消解析',exact:true}).press('Enter');
  await page.getByRole('alertdialog').getByRole('button',{name:/^(确认取消|取消解析|继续取消)$/}).click();
  await card.getByText('正在取消解析',{exact:true}).waitFor();
  await page.evaluate(() => window.resolveTest.finishCancel());
  await page.getByText('粘贴链接开始解析',{exact:true}).waitFor();
  await page.evaluate(() => window.resolveTest.replay());
  await card.waitFor({state:'hidden'});
  check(await input.inputValue() === '', 'cancel did not reset input');
  await load('cache');
  await page.getByText('解析完成的测试作品',{exact:true}).waitFor();
  await page.getByText('解析缓存',{exact:true}).waitFor();
  await card.waitFor({state:'hidden'});
  await load('preflight');
  await card.getByText('解析失败',{exact:true}).waitFor();
  await card.getByRole('alert').waitFor();
  check(await steps.locator('[data-state=done]').count() === 0 && await input.isEnabled(), 'preflight failure invents completed steps or locks input');
  await input.fill('https://www.youtube.com/watch?v=test1234567');
  await card.getByText('www.douyin.com',{exact:true}).waitFor();
  return 'Passed: compact three-step layout, three viewports, real phase grouping, skipped stages, stale reply, navigation, keyboard cancel, Telegram reconnect/failure, cache, preflight error.';
}
