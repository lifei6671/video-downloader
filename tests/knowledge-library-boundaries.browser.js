async page => {
  const results = [];
  const check = (value, message) => { if (!value) throw Error(message); };
  const library = () => page.locator('.knowledge-library');
  const dialog = () => page.getByRole('dialog');
  const ready = () => page.waitForFunction(() => document.querySelector('.library-list')?.getAttribute('aria-busy') === 'false');
  const load = async () => { await page.goto('http://127.0.0.1:1420/tests/fixtures/knowledge-library.html'); await page.getByRole('button', { name: '知识库', exact: true }).click(); await ready(); };
  await page.setViewportSize({ width: 1024, height: 680 }); await load();
  await library().getByRole('button', { name: '分类', exact: true }).click();
  await library().getByRole('button', { name: '管理分类', exact: true }).click();
  const field = dialog().getByRole('textbox', { name: '分类名称' });
  await field.fill('长'.repeat(129)); await dialog().getByRole('button', { name: '新建分类', exact: true }).click();
  await dialog().getByText('分类名称最多 128 个字符', { exact: true }).waitFor();
  await field.fill('汉'.repeat(128)); await dialog().getByRole('button', { name: '新建分类', exact: true }).click();
  await dialog().getByRole('button', { name: '修改分类 ' + '汉'.repeat(128), exact: true }).waitFor();
  await dialog().getByRole('button', { name: '修改分类 开场钩子', exact: true }).click();
  await dialog().getByRole('combobox', { name: '上级分类' }).click();
  check(await page.getByRole('option', { name: '开场钩子', exact: true }).count() === 0, 'self allowed as parent');
  await page.keyboard.press('Escape');
  await dialog().getByRole('button', { name: '修改分类 文案学习', exact: true }).click();
  await dialog().getByRole('combobox', { name: '上级分类' }).click();
  check(await page.getByRole('option', { name: '开场钩子', exact: true }).count() === 0, 'descendant allowed as parent');
  await page.keyboard.press('Escape');
  const box = await dialog().boundingBox();
  const footer = await dialog().getByRole('button', { name: '完成', exact: true }).boundingBox();
  check(box.y >= 0 && box.y + box.height <= 680 && footer.y + footer.height <= box.y + box.height, 'compact dialog footer unreachable');
  await page.screenshot({ path: '.local/wb113-category-dialog-1024.png', animations: 'disabled' });
  await page.keyboard.press('Escape'); await dialog().waitFor({ state: 'hidden' });
  check(await library().getByRole('button', { name: '管理分类', exact: true }).evaluate(node => document.activeElement === node), 'dialog close did not restore focus');
  results.push('128 Unicode name boundary/invalid parent exclusions/compact dialog/footer/Escape focus');

  await load();
  const a2 = library().locator('[data-library-asset="a2"]');
  const a3 = library().locator('[data-library-asset="a3"]');
  await a2.getByRole('checkbox').check(); await a3.getByRole('checkbox').check();
  await library().locator('.library-selection-toolbar').getByRole('button', { name: '分类与标签', exact: true }).click();
  await dialog().getByRole('checkbox', { name: '拍摄手法', exact: true }).check();
  await dialog().getByRole('checkbox', { name: /节奏/ }).check();
  await page.evaluate(() => window.libraryTest.failMethodOnce('setTags'));
  await dialog().getByRole('button', { name: '保存', exact: true }).click();
  await dialog().getByRole('alert').filter({ hasText: '已保存 1 项，其余修改未保存' }).waitFor();
  check(await page.evaluate(() => ['a2', 'a3'].every(id => window.libraryTest.snapshot().assets.find(a => a.id === id).category_ids.includes('c3'))), 'successful category write lost after tag failure');
  const count = await page.evaluate(() => window.libraryTest.calls.filter(call => call.method === 'setCategories').length);
  await dialog().getByRole('button', { name: '保存', exact: true }).click(); await dialog().waitFor({ state: 'hidden' }); await ready();
  check(await page.evaluate(() => window.libraryTest.calls.filter(call => call.method === 'setCategories').length) === count, 'retry repeated successful relationship command');
  check(await page.evaluate(() => ['a2', 'a3'].every(id => window.libraryTest.snapshot().assets.find(a => a.id === id).tag_ids.includes('t1'))), 'retry did not finish tag');
  results.push('partial relationship save accurately reported; retry applies remaining change only');

  await library().getByRole('textbox', { name: '搜索知识库' }).fill('100%_');
  await library().getByRole('button', { name: '搜索', exact: true }).click(); await ready();
  await page.getByRole('button', { name: '下载中心', exact: true }).click();
  const input = page.locator('#video-input'); await input.fill('保留的下载链接');
  await page.getByRole('button', { name: '知识库', exact: true }).click(); await ready();
  check(await library().getByRole('textbox', { name: '搜索知识库' }).inputValue() === '100%_', 'navigation lost library query');
  check(await library().locator('[data-library-asset]').count() === 1, 'navigation lost library filter');
  await page.getByRole('button', { name: '下载中心', exact: true }).click();
  check(await input.inputValue() === '保留的下载链接', 'navigation lost download input');
  results.push('download center and library preserve independent input/filter state');
  return { passed: results.length, cases: results };
}
