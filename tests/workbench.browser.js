  const bench = () => page.getByRole('region', { name: '工作台内容', exact: true });
  const section = name => bench().getByRole('region', { name, exact: true });
  const detail = () => page.getByRole('region', { name: '视频资料详情', exact: true });
  const ready = () => page.waitForFunction(() => document.querySelector('.workbench')?.getAttribute('aria-busy') === 'false');
