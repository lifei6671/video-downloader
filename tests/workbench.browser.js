    await open(); check(await section('最近访问').locator('li').count() === 1, 'opened asset not recorded');
    await section('待分类').getByRole('button', { name: '查看全部', exact: true }).click();
    await page.waitForFunction(() => window.libraryTest.calls.at(-1)?.method !== 'visit' && window.libraryTest.calls.some(c => c.method === 'search' && c.request.uncategorized));
