    await open(); await section('待整理').getByRole('button', { name: '查看全部', exact: true }).click();
    await page.waitForFunction(() => window.libraryTest.calls.some(c => c.method === 'search' && c.request.unorganized));
    check(await page.getByRole('button', { name: '待整理', exact: true, includeHidden: true }).getAttribute('aria-pressed') === 'true', 'wrong organization scope');
    await open();
    await section('运行中操作').getByRole('button', { name: /竖屏文件文案/ }).click(); await detail().waitFor();
    await page.waitForFunction(() => document.querySelector('.library-file-path')?.textContent?.includes('竖屏样本') || [...document.querySelectorAll('.library-asset-detail')].some(el => el.textContent.includes('竖屏样本.mp4')));
    await page.waitForFunction(() => document.activeElement?.matches('.library-detail-title'));
    await open();
    await section('运行中操作').getByRole('button', { name: /竖屏文件文案/ }).click();
