async page => {
  page.setDefaultTimeout(10000);
  const check = (ok, message) => { if (!ok) throw Error(message); };
  const panel = () => page.getByRole('region', { name: '素材文案', exact: true });
  const ready = () => page.waitForFunction(() => document.querySelector('.library-writing')?.getAttribute('aria-busy') === 'false');
  await page.goto('http://127.0.0.1:1420/tests/fixtures/knowledge-library.html?detail=1&writing=1');
  await page.getByRole('button', { name: '素材库', exact: true }).click();
  await page.locator('[data-library-asset="a0"] .library-asset-title').click(); await ready();
  await panel().getByRole('textbox', { name: '原始文案内容' }).fill('自己的冲突稿😀');
  await page.evaluate(() => window.writingTest.remoteEdit('a0'));
  await panel().getByRole('button', { name: '保存', exact: true }).click();
  await panel().getByText('内容已更新，请重新读取后再保存', { exact: true }).waitFor();
  check(await panel().getByRole('textbox', { name: '原始文案内容' }).inputValue() === '自己的冲突稿😀', 'conflict discarded draft');
  await panel().getByRole('button', { name: '读取最新内容', exact: true }).click();
  await panel().getByRole('textbox', { name: '保留内容 1' }).waitFor();
  check(await panel().getByRole('textbox', { name: '保留内容 1' }).inputValue() === '自己的冲突稿😀', 'conflict recovery lost');
  await panel().getByRole('button', { name: '恢复本次输入', exact: true }).click();
  await panel().getByRole('button', { name: '保存', exact: true }).click();
  await panel().getByRole('button', { name: '保存', exact: true, disabled: true }).waitFor();
  await panel().getByRole('textbox', { name: '原始文案内容' }).fill('回读失败的原始文案');
  await page.evaluate(() => window.writingTest.failNext('document'));
  await panel().getByRole('button', { name: '保存', exact: true }).click();
  await panel().getByText(/内容已保存，重新读取失败/).waitFor();
  const count = await page.evaluate(() => window.writingTest.calls.filter(c => c.method === 'saveDocument').length);
  await panel().getByRole('button', { name: '重新读取已保存内容', exact: true }).click(); await ready();
  check(await page.evaluate(() => window.writingTest.calls.filter(c => c.method === 'saveDocument').length) === count, 'read retry repeated write');
  await panel().getByRole('tab', { name: 'AI 总结', exact: true }).click(); await ready();
  await panel().getByRole('textbox', { name: 'AI 总结内容' }).fill('总结保存失败时保留');
  await page.evaluate(() => window.writingTest.failNext('createNote'));
  await panel().getByRole('button', { name: '保存', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.library-writing [data-slot="alert"]'));
  check(await panel().getByRole('textbox', { name: 'AI 总结内容' }).inputValue() === '总结保存失败时保留', 'failed save discarded summary');
  await panel().getByRole('button', { name: '保存', exact: true }).click();
  await panel().getByRole('button', { name: '保存', exact: true, disabled: true }).waitFor();
  await panel().getByRole('tab', { name: '原始文案', exact: true }).click(); await ready();
  await panel().getByRole('button', { name: '重新提取原文', exact: true }).click();
  await page.evaluate(() => window.writingTest.progress('f-a0'));
  await panel().getByText('已识别 3 / 10 段', { exact: true }).waitFor();
  await page.evaluate(() => window.writingTest.complete('a0', 'f-a0'));
  check(await panel().getByRole('textbox', { name: '原始文案内容' }).inputValue() === '回读失败的原始文案', 'recognition replaced current editor');
  await panel().getByRole('button', { name: '读取最新内容', exact: true }).click(); await ready();
  check(await panel().getByRole('textbox', { name: '原始文案内容' }).inputValue() === '新提取的识别原文', 'new recognition unavailable');
  return { passed: 1, cases: ['original conflict / recover draft / post-save read retry / summary save failure / ASR progress / explicit refresh'] };
}
