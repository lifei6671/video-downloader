// Isolated fake credentials, IPC and persistence; never reads real OS credentials.
async page => {
  const base=page.url().split('/').slice(0,3).join('/');
  const check=(value,message)=>{if(!value)throw Error(message)};
  const address=()=>page.getByRole('textbox',{name:'HTTP / SOCKS5 地址',exact:true});
  const save=()=>page.getByRole('button',{name:'保存平台配置',exact:true});
  const mode=name=>page.getByRole('radio',{name,exact:true});
  const snapshot=()=>page.evaluate(()=>window.platformSettingsTest.snapshot());
  const saved=()=>page.getByRole('status').filter({hasText:'平台配置已保存，仅影响新任务'}).waitFor();
  const accounts=async(loaded=true)=>{
    await page.getByRole('button',{name:'系统设置',exact:true}).click();
    await page.getByRole('button',{name:'平台账号',exact:true}).click();
    await page.getByRole('tab',{name:'YouTube',exact:true}).click();
    await page.waitForFunction(()=>!document.querySelector('#youtube-clear')?.disabled);
    if(loaded)await page.waitForFunction(()=>!document.querySelector('#youtube-mode + [data-slot="toggle-group"] button')?.disabled);
  };
  const fresh=async()=>{
    await page.goto(base+'/tests/fixtures/platform-settings.html');
    await page.evaluate(()=>sessionStorage.clear());await page.reload();await accounts();
  };
  const cases=[];
  const credential='http://fixture-user:fixture-pass@127.0.0.1:7890';
  for(const [width,height] of [[1440,900],[1280,800],[1024,680]]) {
    await page.setViewportSize({width,height});await fresh();
    await mode('自定义代理').click();await address().fill('  '+credential+'  ');
    await save().click();await saved();
    check(await address().inputValue()===credential && await save().isDisabled(),'save erased proxy or remained dirty');
    check((await snapshot()).settings.profiles.find(p=>p.platform==='youtube').proxy==='http://127.0.0.1:7890/','public settings contain authenticated URL');
    await page.reload();await accounts();
    check(await address().inputValue()===credential && await save().isDisabled(),'proxy not restored from dedicated read');
    await page.getByRole('textbox',{name:'User-Agent',exact:true}).fill('fixture-updated');
    await save().click();await saved();
    check((await page.evaluate(()=>window.platformSettingsTest.calls.at(-1))).proxy===null,'unchanged authenticated proxy was overwritten');
    check((await snapshot()).proxies.youtube===credential,'UA save lost proxy credentials');
    await mode('直连').click();await mode('自定义代理').click();
    check(await address().inputValue()===credential && await save().isDisabled(),'unsaved mode switch lost proxy');
    await page.getByRole('radio',{name:'自定义',exact:true}).click();
    const header=page.locator('#settings-operation-area > header');
    const tabs=page.getByRole('tablist',{name:'配置平台',exact:true});
    const navigation=page.getByRole('navigation',{name:'设置分类',exact:true});
    const positions=await Promise.all([header.boundingBox(),tabs.boundingBox(),navigation.boundingBox()]);
    const panel=page.getByRole('tabpanel',{name:'YouTube',exact:true});
    await panel.hover();await page.mouse.wheel(0,1600);
    await page.waitForFunction(()=>document.querySelector('.settings-platforms [role="tabpanel"][data-state="active"]').scrollTop>0);
    const after=await Promise.all([header.boundingBox(),tabs.boundingBox(),navigation.boundingBox()]);
    positions.forEach((before,index)=>check(Math.abs(before.y-after[index].y)<1,'heading/tabs/navigation moved at '+width));
    check(await page.locator('[data-slot="page-content"]').evaluate(el=>el.scrollTop)===0,'outer settings page scrolls');
    const panelBox=await panel.boundingBox();
    check(panelBox.y>=after[1].y+after[1].height,'form overlaps fixed tabs');
    check(await save().isVisible(),'save button unreachable after scrolling');
    await page.screenshot({path:'.local/proxy-settings-header-20261021/fixed-'+width+'.png',animations:'disabled'});
    check(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'horizontal overflow');
    await page.getByRole('tab',{name:'YouTube',exact:true}).focus();await page.keyboard.press('ArrowLeft');
    await page.waitForFunction(()=>document.querySelector('.settings-platforms [role="tab"][aria-selected="true"]').textContent==='TikTok');
    check(await page.getByRole('tab',{name:'TikTok',exact:true}).getAttribute('aria-selected')==='true','keyboard tab navigation failed');
    await page.keyboard.press('ArrowRight');
    await page.waitForFunction(()=>document.querySelector('.settings-platforms [role="tab"][aria-selected="true"]').textContent==='YouTube');
    check(await address().inputValue()===credential,'platform tab switch lost proxy draft');
    await mode('直连').click();await save().click();await saved();
    check((await snapshot()).proxies.youtube===null,'direct mode did not clear saved proxy');
    await page.reload();await accounts();
    check(await mode('直连').isChecked(),'direct mode not restored');
    cases.push(width+': authenticated proxy echo/save/reload/preserve/clear; fixed header/tabs/navigation; scroll/keyboard/layout');
  }
  await fresh();await mode('自定义代理').click();await address().fill(credential);await save().click();await saved();
  await page.evaluate(()=>window.platformSettingsTest.failProxy=true);
  await page.getByRole('button',{name:'下载任务',exact:true}).click();await accounts(false);
  await page.getByRole('alert').filter({hasText:'保存其他设置将保留已有代理'}).waitFor();
  check(await address().isDisabled() && await mode('直连').isDisabled(),'read failure permits proxy overwrite');
  await page.getByRole('textbox',{name:'User-Agent',exact:true}).fill('after-read-error');
  await save().click();await saved();
  check((await page.evaluate(()=>window.platformSettingsTest.calls.at(-1))).proxy===null && (await snapshot()).proxies.youtube===credential,'read failure changed saved proxy');
  cases.push('proxy read failure preserves credentials while allowing other settings');
  await page.evaluate(()=>{window.platformSettingsTest.failProxy=false;window.platformSettingsTest.holdProxy=true});
  await page.getByRole('button',{name:'下载任务',exact:true}).click();await accounts(false);
  check(await address().isDisabled(),'pending read permits draft edits');
  await page.getByRole('textbox',{name:'User-Agent',exact:true}).fill('during-proxy-read');
  await save().click();await saved();
  check((await page.evaluate(()=>window.platformSettingsTest.calls.at(-1))).proxy===null,'pending read overwrote proxy');
  await page.evaluate(()=>{window.platformSettingsTest.holdProxy=false;window.platformSettingsTest.releaseProxy()});
  await page.waitForFunction(()=>!document.querySelector('#youtube-proxy').disabled);
  check(await address().inputValue()===credential && await save().isDisabled(),'late read lost persisted proxy or dirtied form');
  cases.push('delayed read safely restores credentials after another field is saved');
  await address().fill('socks5://127.0.0.1:1080');
  await page.evaluate(()=>window.platformSettingsTest.failSave=true);await save().click();
  await page.getByRole('alert').filter({hasText:'无法保存任务记录'}).waitFor();
  check(await address().inputValue()==='socks5://127.0.0.1:1080' && (await snapshot()).proxies.youtube===credential,'failed save lost draft or changed stored credentials');
  await page.evaluate(()=>window.platformSettingsTest.failSave=false);await save().click();await saved();
  check(await address().inputValue()==='socks5://127.0.0.1:1080' && await save().isDisabled(),'corrected proxy save not reflected in editor');
  cases.push('failed save preserves old proxy and retryable draft');
  return {passed:cases.length,cases};
}
