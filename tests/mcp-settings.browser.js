async page => {
  page.setDefaultTimeout(8000);
  const check = (ok, message) => { if (!ok) throw Error(message); };
  const results = [];
  const panel = () => page.locator('.mcp-settings');
  const toggle = () => panel().getByRole('switch', { name: '启用 MCP' });
  const copy = () => panel().getByRole('button', { name: '复制配置', exact: true });
  const refresh = () => panel().getByRole('button', { name: '刷新状态' });
  const settings = async () => { await page.getByRole('button', { name: '系统设置', exact: true }).click(); await page.getByRole('navigation', { name: '设置分类' }).getByRole('button', { name: 'MCP', exact: true }).click(); await panel().getByText('已关闭', { exact: true }).waitFor(); };
  const load = async (extra = '') => { await page.goto('http://127.0.0.1:1420/tests/fixtures/knowledge-library.html?mcp=1' + extra); await settings(); };
  for (const [width, height] of [[1440, 900], [1280, 800], [1024, 680]]) {
    await page.setViewportSize({ width, height }); await load();
    check(await toggle().getAttribute('aria-checked') === 'false', 'must default off');
    check(await copy().isDisabled(), 'off service can copy config');
    check(await panel().getByRole('radio', { name: 'Codex（TOML）' }).getAttribute('aria-checked') === 'true', 'wrong default format');
    await toggle().focus(); await page.keyboard.press('Space'); await panel().getByText('运行中', { exact: true }).waitFor();
    await copy().click(); await panel().getByText('配置已复制', { exact: true }).waitFor();
    check((await page.evaluate(() => window.mcpTest.copies.at(-1))).startsWith('[mcp_servers.yingqu]'), 'TOML copy mismatch');
    await panel().getByRole('radio', { name: 'Codex（TOML）' }).focus(); await page.keyboard.press('ArrowRight'); await page.waitForFunction(() => document.activeElement?.textContent === '通用 JSON'); await page.keyboard.press('Enter');
    await panel().getByRole('radio', { name: '通用 JSON' }).waitFor(); await copy().click();
    const json = JSON.parse(await page.evaluate(() => window.mcpTest.copies.at(-1)));
    check(json.mcpServers.yingqu.command === 'C:\\Program Files\\中文 映取\\yingqu-mcp.exe', 'path with spaces changed');
    check(json.mcpServers.yingqu.args.length === 2 && json.mcpServers.yingqu.args[0] === '--endpoint', 'args flattened');
    check(await panel().getByRole('button', { name: '复制配置' }).isEnabled(), 'copy became unavailable');
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'horizontal overflow');
    const pre = panel().getByLabel('客户端配置内容');
    check(await pre.evaluate(el => el.scrollWidth <= el.clientWidth), 'config text overflow');
    await page.screenshot({ path: '.local/wb206/settings-' + width + '.png', fullPage: true });
    results.push({ viewport: width, defaultOff: 'PASS', keyboardAndCopy: 'PASS', layout: 'PASS' });
  }
  await load();
  await page.evaluate(() => window.mcpTest.failNext('IPC_BIND_FAILED'));
  await toggle().click(); await panel().getByRole('alert').getByText('MCP 服务启动失败，请重试。').waitFor();
  check(await toggle().getAttribute('aria-checked') === 'false', 'failed enable looked successful');
  await page.evaluate(() => window.mcpTest.hold('set')); await toggle().click(); await panel().getByText('正在开启…', { exact: true }).waitFor();
  check(await toggle().isDisabled() && await copy().isDisabled(), 'pending controls remain active');
  await page.evaluate(() => window.mcpTest.release()); await panel().getByText('运行中', { exact: true }).waitFor();
  await page.evaluate(() => window.mcpTest.failNext('CLIPBOARD_WRITE_FAILED')); await copy().click(); await panel().getByText('复制失败，请重试。', { exact: true }).waitFor();
  await copy().click(); await panel().getByText('配置已复制', { exact: true }).waitFor();
  await page.evaluate(() => { window.mcpTest.hold('read'); window.dispatchEvent(new Event('focus')); });
  await toggle().click(); await panel().getByText('已关闭', { exact: true }).waitFor();
  await page.evaluate(() => window.mcpTest.release());
  check(await toggle().getAttribute('aria-checked') === 'false' && await copy().isDisabled(), 'stale read revived stopped service');
  await toggle().click(); await panel().getByText('运行中', { exact: true }).waitFor();
  await page.getByRole('button', { name: '工作台', exact: true }).click();
  await page.getByRole('button', { name: '系统设置', exact: true }).click();
  await panel().getByText('运行中', { exact: true }).waitFor();
  await page.evaluate(() => window.mcpTest.stop()); await panel().getByText('服务异常', { exact: true }).waitFor();
  check(await copy().isDisabled(), 'failed listener kept config');
  await toggle().click(); await panel().getByText('运行中', { exact: true }).waitFor();
  await page.evaluate(() => window.mcpTest.failNext('IO_ERROR')); await toggle().click();
  await panel().getByText('操作失败，请重试。', { exact: true }).waitFor();
  check(await toggle().getAttribute('aria-checked') === 'true', 'failed disable changed state');
  await page.evaluate(() => window.mcpTest.hold('set')); await toggle().click(); await panel().getByText('正在关闭…', { exact: true }).waitFor();
  await page.evaluate(() => window.mcpTest.release()); await panel().getByText('已关闭', { exact: true }).waitFor();
  results.push({ failuresRetryPendingStaleReadsAndDisconnect: 'PASS' });
  await load('&missing=1');
  await panel().getByRole('alert').getByText(/未找到 MCP 适配程序/).waitFor();
  check(await toggle().isDisabled() && await copy().isDisabled(), 'missing adapter controls enabled');
  await page.evaluate(() => window.mcpTest.installed(true)); await refresh().click(); check(await toggle().isEnabled(), 'adapter refresh did not recover');
  await page.evaluate(() => window.mcpTest.failRead(true)); await refresh().click(); await panel().getByText('状态不可用', { exact: true }).waitFor();
  check(await toggle().isDisabled(), 'read failure allowed mutation');
  await page.evaluate(() => window.mcpTest.failRead(false)); await refresh().click(); await panel().getByText('已关闭', { exact: true }).waitFor();
  results.push({ missingAdapterAndReadRecovery: 'PASS' });
  return results;
}
