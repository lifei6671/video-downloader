// Run with Playwright CLI against ONLY the marked p1a-wb303-final-upgrade WebView2.
async page => {
  const browser = await page.context().browser().browserType().connectOverCDP('http://127.0.0.1:9333');
  const p = browser.contexts()[0].pages().find(value => value.url() === 'http://127.0.0.1:1420/');
  if (!p) throw Error('Isolated Tauri page not found');
  p.setDefaultTimeout(10000);
  const check = (ok, message) => { if (!ok) throw Error(message); }, results = [];
  const invoke = (command, args = {}) => p.evaluate(({ command, args }) => window.__TAURI_INTERNALS__.invoke(command, args), { command, args });
  const settings = await invoke('get_settings');
  check(settings.download_directory.includes('wb303-final'), 'not isolated WB303 profile');
  const assets = await invoke('search_library_assets', { request: {} });
  const assetId = assets.items.find(value => value.asset.video_id === '7300000000000000001').asset.id;
  for (const row of await invoke('list_library_clips', { assetId })) await invoke('delete_library_clip', { assetId, clipId: row.id });
  const data = await invoke('get_library_asset', { assetId });
  const original = data.files.find(file => file.path.endsWith('原视频.mp4'));
  const special = data.files.find(file => file.path.endsWith('另一个版本.mp4'));
  const document = data.documents.find(value => value.kind === 'recognized');
  await p.getByRole('button', { name: '知识库', exact: true }).click();
  const existing = p.getByRole('region', { name: '视频资料详情', exact: true });
  if (await existing.isVisible()) await existing.getByRole('button', { name: '返回列表', exact: true }).click();
  await p.locator('[data-library-asset="' + assetId + '"]').getByRole('button', { name: /^查看视频资料/ }).click();
  const detail = p.getByRole('region', { name: '视频资料详情', exact: true });
  const clips = p.getByRole('region', { name: '片段收藏', exact: true });
  const video = detail.locator('video');
  const choose = async filename => { await detail.getByRole('combobox', { name: '文件版本', exact: true }).click(); await p.getByRole('option').filter({ hasText: filename }).click(); };
  await choose('原视频.mp4');
  await p.waitForFunction(() => document.querySelector('.library-writing')?.getAttribute('aria-busy') === 'false');
  await detail.getByRole('textbox', { name: '识别原文全文', exact: true }).evaluate(el => { el.focus(); el.setSelectionRange(0, 6); document.dispatchEvent(new Event('selectionchange')); });
  await detail.getByRole('button', { name: '引用所选文字收藏片段', exact: true }).click();
  await p.waitForFunction(() => [...document.querySelectorAll('.library-clips button')].some(b => b.textContent === '标为开始' && !b.disabled));
  await clips.getByRole('textbox', { name: '片段标题', exact: true }).fill('原生引用收藏😀');
  await clips.getByRole('textbox', { name: '片段开始时间', exact: true }).fill('0.4');
  await clips.getByRole('textbox', { name: '片段结束时间', exact: true }).fill('1.2');
  await clips.getByRole('textbox', { name: '收藏理由', exact: true }).fill('验证稳定原文与文件绑定');
  await clips.getByRole('button', { name: '保存片段', exact: true }).click(); await clips.locator('form').waitFor({ state: 'hidden' });
  const first = (await invoke('list_library_clips', { assetId }))[0];
  check(first.file_id === original.id && first.document_id === document.id && first.document_version === document.version, 'native citation binding');
  await clips.getByRole('button', { name: '播放片段', exact: true }).click(); await detail.getByText('片段播放完成', { exact: true }).waitFor();
  check(await video.evaluate(v => v.paused && Math.abs(v.currentTime - 1.2) < .05), 'native asset protocol range stop');
  check(await video.getAttribute('src').then(value => value.startsWith('http://asset.localhost/')), 'not Tauri asset protocol');
  results.push('production Tauri commands, native SQLite, immutable citation and asset-protocol playback 0.4–1.2s');
  const invalid = { file_id: special.id, title: 'wrong source', reason: '', start_ms: 5200, end_ms: 6600, playable: { start_ms: 5000, end_ms: 11000 }, document_id: document.id, quote: first.quote };
  const failure = await p.evaluate(args => window.__TAURI_INTERNALS__.invoke('create_library_clip', args).then(() => '', reason => String(reason)), { assetId, input: invalid });
  check(failure === 'CLIP_SOURCE_MISMATCH', 'native command allowed wrong file citation');
  await choose('另一个版本.mp4'); await clips.getByRole('button', { name: '收藏片段', exact: true }).click();
  await clips.getByText(/^可播放范围：00:05.000–/).waitFor();
  await clips.getByRole('textbox', { name: '片段标题', exact: true }).fill('原生正 PTS 收藏');
  await clips.getByRole('textbox', { name: '片段开始时间', exact: true }).fill('0.2');
  await clips.getByRole('textbox', { name: '片段结束时间', exact: true }).fill('6');
  check(await clips.getByRole('button', { name: '保存片段', exact: true }).isDisabled(), 'native positive PTS head accepted');
  await clips.getByRole('textbox', { name: '片段开始时间', exact: true }).fill('5.2');
  await clips.getByRole('textbox', { name: '片段结束时间', exact: true }).fill('6.6');
  await clips.getByRole('button', { name: '保存片段', exact: true }).click(); await clips.locator('form').waitFor({ state: 'hidden' });
  await clips.getByRole('listitem').filter({ hasText: '原生正 PTS 收藏' }).getByRole('button', { name: '播放片段', exact: true }).click();
  await detail.getByText('片段播放完成', { exact: true }).waitFor();
  check(await video.evaluate(v => v.paused && Math.abs(v.currentTime - 6.6) < .05), 'native special MP4 stop');
  // Simulate a range saved by another media renderer with a different capability.
  await invoke('create_library_clip', { assetId, input: { ...invalid, document_id: null, quote: null, title: '原生不可播放范围', end_ms: 20000, playable: { start_ms: 5000, end_ms: 20000 } } });
  await clips.getByRole('listitem').filter({ hasText: '原生不可播放范围' }).getByRole('button', { name: '播放片段', exact: true }).click();
  await detail.getByRole('alert').filter({ hasText: '片段无法完整播放' }).waitFor();
  check(await video.evaluate(v => v.paused), 'native invalid range played');
  check((await invoke('list_library_clips', { assetId })).find(c => c.title === '原生不可播放范围').end_ms === 20000, 'native shortened saved range');
  results.push('native positive-PTS MP4 lower-bound probe, 5.2–6.6s playback, wrong file citation and 20s range rejection');
  await clips.getByRole('listitem').filter({ hasText: '原生引用收藏😀' }).getByRole('button', { name: '查看引用原文 v1', exact: true }).click();
  check(await p.getByRole('textbox', { name: '引用文案全文', exact: true }).inputValue().then(text => text.includes('中文迁移原文')), 'native citation text'); await p.keyboard.press('Escape');
  await detail.getByRole('button', { name: '返回列表', exact: true }).click();
  await p.screenshot({ path: 'output/playwright/wb303-native.png', animations: 'disabled' });
  const rows = await invoke('list_library_clips', { assetId });
  await browser.close();
  return { status: 'PASSED', nativeTauri: true, assetId, originalFile: original.id, specialFile: special.id, documentId: document.id, clips: rows, cases: results };
}
